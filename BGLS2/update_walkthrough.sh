# Implementation Walkthrough

> [!NOTE]
> Addressed the API flow mapping and missing field injections (`date_of_loan`, `deposit_account_no`, etc.) across BOTH `CustomerAccountOpeningActivity` and `CorporateCustomerAccountOpeningActivity` to perfectly match the JSON payloads dynamically generated by `CustomerOnboarding.html` on the web interface.

## Changes Made

### 1. Replicated Web's Two-Stage Save Process
On the web application (`CustomerOnboarding.html`), submitting the Account Details form requires **two sequential backend calls**:
1. It sends the `formData` to `AccountDetailNxt`.
2. Within the success callback of `AccountDetailNxt`, it invokes either `addLeaseAccount` (for Loan Accounts) or `depositAddCust` (for Deposit Accounts).

**Android Bug Addressed:** 
Previously, the Retail app bypassed `AccountDetailNxt` and only called `addLeaseAccount`/`depositAddCust`. Meanwhile, the Corporate app bypassed `addLeaseAccount`/`depositAddCust` and ONLY called `AccountDetailNxt`. 
- **Fix**: Re-wrote the `saveAccountDetails()` function for BOTH Retail and Corporate. Now, they successfully map the `formData`, make the initial save via `RetrofitClient.api.saveAccountDetails(...)`, and within its `isSuccessful` block, route correctly to `addLeaseAccount` (if LA) or `depositAddCust` (if TD), perfectly mirroring the backend logic.

### 2. Accurate API Payload Mapping
> [!IMPORTANT]
> The backend failed to store fields like `date_of_loan` because they were missing from the injected `formData` mapping sent to `AccountDetailNxt`.
- **Date of Loan (`date_of_loan`)**: Injected into the Loan Account segment of the formData payload, properly converted to the required backend format using `formatDateForBackend`.
- **Deposit Fields**: Integrated missing Deposit fields mapping across UI interactions, ensuring `etDepositAccountNo` maps directly into `deposit_account_no` (which goes into the Web's `AccountDetailNxt` API) and into `depo_actno` (which goes into the `depositAddCust` API).

### 3. Corporate Activity UI Alignment
- Injected the missing Deposit fields inside `activity_corporate_customer_account_opening.xml` mapping exactly to the web.
- Integrated standard automatic calculation algorithms (e.g., drawing limit deduction, EMIs, Deposit Interest calculations) dynamically within `setupCalculations()`.
- Tied visibility logic inside `setupSpinners()` to seamlessly toggle between Loan Account forms and Deposit Account forms whenever `"DEPOSIT ACCOUNT"` is dynamically selected.

